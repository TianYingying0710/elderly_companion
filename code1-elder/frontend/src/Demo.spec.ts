import { mount, flushPromises } from '@vue/test-utils'
import { afterEach, expect, it, vi } from 'vitest'
import App from './App.vue'

afterEach(() => vi.unstubAllGlobals())
const boot = () => { vi.stubGlobal('fetch', vi.fn().mockRejectedValue(new Error('offline'))); return mount(App) }
it('handles native back on an inner page and lets native handle the root', async () => {
  const w=boot()
  await w.get('[data-testid="nav-learn"]').trigger('click')
  const event=new Event('elder-back',{cancelable:true}); window.dispatchEvent(event)
  await flushPromises()
  expect(event.defaultPrevented).toBe(true)
  expect(w.text()).toContain('今日提醒')
  const root=new Event('elder-back',{cancelable:true}); window.dispatchEvent(root)
  expect(root.defaultPrevented).toBe(false)
  w.unmount()
})
it('closes the SOS confirmation before navigating on native back', async () => {
  const w = boot()
  await w.get('[data-testid="help"]').trigger('click')
  expect(w.find('[role="dialog"]').exists()).toBe(true)
  const event = new Event('elder-back', { cancelable: true })
  window.dispatchEvent(event)
  await flushPromises()
  expect(event.defaultPrevented).toBe(true)
  expect(w.find('[role="dialog"]').exists()).toBe(false)
  expect(w.text()).toContain('今日提醒')
  w.unmount()
})
it('applies large text across navigation and keeps it on secondary pages', async () => {
  const w=boot()
  await w.get('[data-testid="nav-me"]').trigger('click')
  await w.get('[data-testid="settings"]').trigger('click')
  await w.get('[data-testid="large-font"]').trigger('click')
  await w.get('[data-testid="nav-learn"]').trigger('click')
  expect(w.get('.app').classes()).toContain('large')
})
it('isolates demo content and resets drafts and requests when disabled', async () => {
  const w = boot()
  expect(w.text()).toContain('演示模式')
  expect(w.text()).toContain('林奶奶')
  await w.get('[data-testid="mode-toggle"]').trigger('click')
  expect(w.text()).not.toContain('林奶奶')
  await w.get('[data-testid="nav-chat"]').trigger('click')
  expect(w.text()).not.toContain('手机叫车')
  expect(w.text()).toContain('尚未接入')
  expect(fetch).not.toHaveBeenCalled()
})
it('filters courses and opens the selected course', async () => {
  const w = boot()
  await w.get('[data-testid="nav-learn"]').trigger('click')
  await w.get('input[type="search"]').setValue('叫车')
  expect(w.findAll('[data-testid="course-item"]')).toHaveLength(1)
  await w.get('[data-testid="course-item"]').trigger('click')
  expect(w.text()).toContain('没有真实视频')
})
it('retries and cancels a simulated SOS, retaining the cancellation record', async () => {
  const w = boot()
  await w.get('[data-testid="help"]').trigger('click')
  await w.get('[data-testid="confirm-help"]').trigger('click')
  await w.get('[data-testid="fail-help"]').trigger('click')
  await w.get('[data-testid="retry-help"]').trigger('click')
  await w.get('[data-testid="deliver-help"]').trigger('click')
  await w.get('[data-testid="respond-help"]').trigger('click')
  await w.get('[data-testid="cancel-help"]').trigger('click')
  await w.get('[data-testid="confirm-cancel"]').trigger('click')
  expect(w.text()).toContain('求助已取消')
  await w.get('[data-testid="help-records"]').trigger('click')
  expect(w.text()).toContain('同步取消')
  await w.get('[data-testid="mode-toggle"]').trigger('click')
  expect(w.text()).not.toContain('同步取消')
})
it('renders input as text without generating an AI reply', async () => {
  const w = boot()
  await w.get('[data-testid="nav-chat"]').trigger('click')
  await w.get('textarea').setValue('<img src=x onerror=alert(1)>')
  await w.get('form').trigger('submit')
  expect(w.find('.messages img').exists()).toBe(false)
  expect(w.text()).toContain('<img src=x onerror=alert(1)>')
  expect(w.text()).toContain('本地草稿')
  expect(fetch).not.toHaveBeenCalled()
  await flushPromises()
})
